/**
 * MediaPipe ships its vision wasm runtime inside node_modules. Vite only serves
 * files under public/, so mirror the runtime there before dev/build.
 *
 * The destination directory carries the package version. Everything under
 * public/ is copied verbatim by Vite -- no content hashing -- and the deploy
 * serves it with `max-age=31536000, immutable`, so an unversioned path would
 * pin the first runtime a visitor ever downloaded for a year. FilesetResolver
 * builds its own filenames beneath whatever directory it is given, so the
 * version has to live in the directory rather than in the file names.
 *
 * ~18MB, so it is gitignored and re-copied rather than committed.
 */
import { cp, mkdir, readFile, readdir, rm, stat, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
// The package's `exports` map hides package.json, so resolve it by path. The
// workspace uses node-linker=hoisted, so it lives at the monorepo root.
const pkgDir = resolve(root, '../../node_modules/@mediapipe/tasks-vision');

let version;
try {
  version = JSON.parse(await readFile(resolve(pkgDir, 'package.json'), 'utf8')).version;
} catch {
  console.error('[mediapipe] @mediapipe/tasks-vision is not installed; run an install first.');
  process.exit(1);
}

const src = resolve(pkgDir, 'wasm');
const parent = resolve(root, 'public/mediapipe');
const dest = resolve(parent, `wasm-${version}`);

if (!(await stat(src).catch(() => null))) {
  console.error(`[mediapipe] wasm runtime not found at ${src}`);
  process.exit(1);
}

// Drop stale versions so public/ does not accumulate 18MB per upgrade.
for (const entry of await readdir(parent).catch(() => [])) {
  if (entry.startsWith('wasm-') && entry !== `wasm-${version}`) {
    await rm(resolve(parent, entry), { recursive: true, force: true });
    console.log(`[mediapipe] removed stale ${entry}`);
  }
}

// The app needs the directory name. Emitting a real module beats vite's
// `define`, which is not applied to dev-served source here, and beats a runtime
// manifest fetch, which would add a round-trip before the model can load. The
// file is committed so a bare `vite` still works; this rewrites it on version
// changes.
const generated = resolve(root, 'src/mediapipe-runtime.ts');
const contents =
  `// GENERATED by scripts/copy-mediapipe-wasm.mjs -- do not edit by hand.\n` +
  `// public/ is served immutable for a year with no content hash, so the wasm\n` +
  `// runtime lives in a version-stamped directory.\n` +
  `export const MEDIAPIPE_WASM_DIR = 'mediapipe/wasm-${version}';\n`;
if ((await readFile(generated, 'utf8').catch(() => null)) !== contents) {
  await writeFile(generated, contents);
  console.log(`[mediapipe] wrote src/mediapipe-runtime.ts (wasm-${version})`);
}

if (await stat(resolve(dest, 'vision_wasm_internal.wasm')).catch(() => null)) {
  console.log(`[mediapipe] wasm-${version} already present, skipping copy`);
  process.exit(0);
}

await mkdir(dest, { recursive: true });
await cp(src, dest, { recursive: true });
console.log(`[mediapipe] copied vision wasm runtime -> public/mediapipe/wasm-${version}`);
